// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the radar may rank, strongest implied value first. A protocol
// is rankable when it records no token (no market cap, no CoinGecko id, no symbol) and is not a
// wrapped, staked or bridged product of a token that already trades: the same exclusion the
// watchlist itself uses (its category, its name's words, a version marker, an exchange's name),
// applied to the whole board, not only to the watchlist. A wrapped product's token already
// trades, so ranking it as a launch that has not happened yet would be the radar lying to its
// reader. The watchlist is the floor: every one of its 40 slugs is on the board, and the board
// adds every other rankable protocol below the floor, so the early radar is the whole field the
// snapshot can see, not a hand-picked top.
//
// Implied value is one formula of the snapshot's own figures, the same for every row:
//
//   tier     = 0.35 while tvl_usd < $100M, 0.28 below $1B, 0.20 above it
//   growth   = clamp(change_7d, -50, 150) per cent
//   growthM  = 1 + (growth / 100) x 0.6
//   maturity = 0.5 + min(age_days, 1460) / 1460 x 0.5   (age unknown: 365 days)
//   reach    = 0.9 + min(chains, 20) / 20 x 0.2
//   implied  = max(1, round(tvl_usd x tier x growthM x maturity x reach))
//
// The tier multiple falls as TVL grows: a small protocol's launch is priced on its growth, a
// large one's on its size. Growth is clamped because one week's spike is not a valuation. Age
// is the time since the protocol was first listed, the record of how long it has run with no
// token: the longer it has run at size with no token, the more pent-up the launch. Reach is
// how many chains it runs on: a launch lands wider when the protocol already does. No protocol
// name is ever special-cased, and no row is ever hand-picked: the same function scores all.
//
// The live-token protocols are kept apart and shown with the market's own values (their market
// cap), never mixed into the ranked board: a price that trades is a fact, not a model.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

